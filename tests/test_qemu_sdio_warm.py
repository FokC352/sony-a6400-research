"""QEMU ``sony-a6400`` mmc1 SDIO host: the E0410 negative contract.

``mmc1`` is the SDIO/Wi-Fi host at ``0xF0301000`` with GIC IRQ 221 (E0650: ``udif_devices``
``mmc0 0xF0300000/218``, ``mmc1 0xF0301000/221``, ``mmc2 0xF0302000/224``,
``emmc0 0xF0304000/227``).  The board now models a real SDHCI controller there with **no card**
by default.  The camera's custom-OS hardware branch opens slot 1, sends CMD5 and has no responder,
so the controller reports a command timeout and raises IRQ 221 -- the E0410
``mmcio: mmcio_mount failed`` symptom, reproduced from real controller semantics rather than an
injected fault.

These tests drive the controller through qtest and read the SDHCI status and the GIC pending word.
A positive (card answers CMD5) test needs an SDIO card model, which QEMU's ``sd.c`` does not have;
that is a separate opt-in, not part of this contract.
"""

import unittest

from tests.test_qemu_emmc import NATIVE_AVAILABLE
from tests import test_qemu_liveview

MMC1 = 0xF0301000
MMC2 = 0xF0302000            # unmodelled sibling, the negative control
GICD_CTLR = 0xF8001000
GICD_ISENABLER6 = 0xF8001118   # enable word for hardware ID 221 (SPI 189)
# The distributor's pending words are indexed by the hardware interrupt ID: the machine's
# pic[221-32] is SPI 189, i.e. ID 221, so the bit is in word 221/32 = 6 at bit 221%32 = 29.
GICD_PENDING6 = 0xF8001218
IRQ221_BIT = 1 << 29

SDHC_ARGUMENT = 0x08
SDHC_TRNMOD = 0x0C
SDHC_CMDREG = 0x0E
SDHC_PRNSTS = 0x24
SDHC_PWRCON = 0x29
SDHC_CLKCON = 0x2C
SDHC_NORINTSTS = 0x30
SDHC_NORINTSTSEN = 0x34
SDHC_NORINTSIGEN = 0x38

NIS_ERR = 0x8000
EIS_CMDTIMEOUT = 0x0001
CARD_PRESENT = 0x00010000


@unittest.skipUnless(NATIVE_AVAILABLE, 'Optional WSL/Linux sony-a6400 QEMU build absent')
class QemuMmc1SdioTests(unittest.TestCase):
    start_qtest = test_qemu_liveview.QemuLiveViewPipelineTests.start_qtest
    _stop_proc = test_qemu_liveview.QemuLiveViewPipelineTests._stop_proc
    qtest = test_qemu_liveview.QemuLiveViewPipelineTests.qtest

    def cmd5(self, proc, pending, base):
        q = lambda text: self.qtest(proc, pending, text)
        # The GIC distributor is off at reset (no guest ran); enable it and SPI 189 so the
        # controller's IRQ line latches a pending bit that qtest can read.
        q(f'writel {GICD_CTLR:#x} 0x1')
        q(f'writel {GICD_ISENABLER6:#x} {IRQ221_BIT:#x}')
        q(f'writeb {base + SDHC_PWRCON:#x} 0x0f')      # bus power on, 3.3 V
        q(f'writew {base + SDHC_CLKCON:#x} 0x0007')    # internal clock + SD clock on
        # 0x34/0x38 carry the normal enables in the low half and the error enables in the
        # high half; the timeout path needs the error-status and error-signal bits.
        q(f'writel {base + SDHC_NORINTSTSEN:#x} 0xffffffff')
        q(f'writel {base + SDHC_NORINTSIGEN:#x} 0xffffffff')
        q(f'writel {base + SDHC_ARGUMENT:#x} 0x0')     # CMD5 argument
        # CMD5 with a 48-bit response request. The command is generated by a write that
        # covers the upper byte of CMDREG, i.e. the 32-bit TRNMOD/CMDREG pair (QEMU
        # sdhci_write: "writing to the upper byte of CMDREG triggers command generation").
        q(f'writel {base + SDHC_TRNMOD:#x} 0x050a0000')

    def test_mmc1_controller_is_mapped_without_a_card(self):
        proc, _ = self.start_qtest('sony-a6400')
        pending = [b'']
        present = self.qtest(proc, pending, f'readl {MMC1 + SDHC_PRNSTS:#x}')
        self.assertNotEqual(present, 0, 'mmc1 PRESENT_STATE reads 0 (controller not mapped)')
        self.assertEqual(present & CARD_PRESENT, 0, f'no card expected, got 0x{present:08x}')
        # The unmodelled sibling still reads through the catch-all (0), so the check discriminates.
        self.assertEqual(self.qtest(proc, pending, f'readl {MMC2 + SDHC_PRNSTS:#x}'), 0)

    def test_cmd5_without_a_card_times_out_and_raises_irq221(self):
        proc, _ = self.start_qtest('sony-a6400')
        pending = [b'']
        self.cmd5(proc, pending, MMC1)
        status = self.qtest(proc, pending, f'readw {MMC1 + SDHC_NORINTSTS:#x}')
        self.assertTrue(status & NIS_ERR, f'NIS_ERR not set: 0x{status:04x}')
        self.assertTrue(status & EIS_CMDTIMEOUT, f'CMDTIMEOUT not set: 0x{status:04x}')
        gic = self.qtest(proc, pending, f'readl {GICD_PENDING6:#x}')
        self.assertTrue(gic & IRQ221_BIT, f'IRQ 221 not pending in GICD_ISPENDR5: 0x{gic:08x}')

    def test_unmodelled_sibling_raises_no_irq(self):
        proc, _ = self.start_qtest('sony-a6400')
        pending = [b'']
        self.cmd5(proc, pending, MMC2)
        status = self.qtest(proc, pending, f'readw {MMC2 + SDHC_NORINTSTS:#x}')
        self.assertEqual(status, 0, f'unmodelled sibling reported status 0x{status:04x}')
        gic = self.qtest(proc, pending, f'readl {GICD_PENDING6:#x}')
        self.assertEqual(gic & IRQ221_BIT, 0, f'IRQ 221 pending without mmc1 activity: 0x{gic:08x}')

    def test_ramboot_quiesce_sequence_clears_host_and_gic(self):
        """The ramboot mmc1 quiesce writes leave the host and IRQ 221 quiet (E0688)."""
        proc, _ = self.start_qtest('sony-a6400')
        pending = [b'']
        q = lambda text: self.qtest(proc, pending, text)
        self.cmd5(proc, pending, MMC1)
        self.assertTrue(q(f'readl {GICD_PENDING6:#x}') & IRQ221_BIT)
        # Same order as ramboot.c mmc_quiesce(): enables off, W1C status, clock/power off,
        # software reset, then GIC pending/enable clear for SPI 221.
        q(f'writel {MMC1 + SDHC_NORINTSTSEN:#x} 0x0')
        q(f'writel {MMC1 + SDHC_NORINTSIGEN:#x} 0x0')
        q(f'writel {MMC1 + SDHC_NORINTSTS:#x} 0xffffffff')
        q(f'writew {MMC1 + SDHC_CLKCON:#x} 0x0')
        q(f'writeb {MMC1 + SDHC_PWRCON:#x} 0x0')
        q(f'writeb {MMC1 + 0x2f:#x} 0x1')
        q(f'writel {MMC1 + SDHC_NORINTSTS:#x} 0xffffffff')
        q('writel 0xF8001298 0x20000000')      # GICD_ICPENDR6: SPI 221
        q('writel 0xF8001198 0x20000000')      # GICD_ICENABLER6: SPI 221
        self.assertEqual(q(f'readw {MMC1 + SDHC_NORINTSTS:#x}'), 0)
        self.assertEqual(q(f'readb {MMC1 + 0x2f:#x}'), 0, 'software reset did not complete')
        self.assertEqual(q(f'readb {MMC1 + SDHC_PWRCON:#x}'), 0)
        self.assertEqual(q(f'readl {GICD_PENDING6:#x}') & IRQ221_BIT, 0)
        self.assertEqual(q('readl 0xF8001118') & IRQ221_BIT, 0, 'SPI 221 still enabled')


if __name__ == '__main__':
    unittest.main()


